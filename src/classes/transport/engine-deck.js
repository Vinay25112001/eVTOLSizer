const ALTS = [...new Set(DECK_ROWS.map(r => r[1]))].sort((a, b) => a - b);
const BY_ALT = Object.fromEntries(ALTS.map(h => [h, DECK_ROWS.filter(r => r[1] === h).sort((a, b) => a[0] - b[0])]));

function alongMach(rows, M, col) {
  if (M <= rows[0][0]) return rows[0][col];
  const last = rows[rows.length - 1];
  if (M >= last[0]) return last[col];
  for (let i = 1; i < rows.length; i++)
    if (M <= rows[i][0]) {
      const a = rows[i - 1], b = rows[i], t = (M - a[0]) / (b[0] - a[0]);
      return a[col] + t * (b[col] - a[col]);
    }
  return last[col];
}

function lookup(M, hFt, col) {
  const h = Math.min(Math.max(hFt, ALTS[0]), ALTS[ALTS.length - 1]);
  let i = ALTS.findIndex(x => x >= h);
  if (ALTS[i] === h) return alongMach(BY_ALT[h], M, col);
  const h0 = ALTS[i - 1], h1 = ALTS[i], t = (h - h0) / (h1 - h0);
  return (1 - t) * alongMach(BY_ALT[h0], M, col) + t * alongMach(BY_ALT[h1], M, col);
}

/* Shape of the deck at (Mach, altitude in ft). */
export function deckShape(M, hFt) {
  return {
    maxThrustRatio: lookup(M, hFt, 2),
    tsfcRatio: lookup(M, hFt, 3),
    idleThrustRatio: lookup(M, hFt, 4),
    idleFuelPerLbf: lookup(M, hFt, 5),
  };
}
